// Russian letters to Latin (simplified ICAO-like transliteration), for workspace addresses.
const TRANSLIT: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z", и: "i", й: "y",
  к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r", с: "s", т: "t", у: "u", ф: "f",
  х: "kh", ц: "ts", ч: "ch", ш: "sh", щ: "shch", ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
};

/**
 * Suggests a workspace address from its name: "Зерно & Co" → "zerno-co". The result may still
 * be too short for the server pattern; the form then asks the person to type one.
 */
export function slugify(name: string): string {
  const latin = Array.from(name.toLowerCase(), (ch) => TRANSLIT[ch] ?? ch).join("");
  return latin
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40)
    .replace(/-+$/g, "");
}
